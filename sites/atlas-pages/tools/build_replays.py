#!/usr/bin/env python3
"""Export a few real three-cube test episodes as compact replay data (data/replays.js).

Source: experiments/self_imitation/stack_phased_8h_20261023/final_test/seed1_test3_traces/<seed>.npz
(phase-based BC trained on two-cube demonstrations, reserved test 23 Oct 2026, seed 1: 62/100).
Trace columns (method.py, evaluate()):
  0 t | 1 stage | 2 phase | 3 completion prob | 4-12 cube xyz x3 | 13-15 gripper (eef) xyz |
  16-22 action (22 = gripper command) | 23-25 held x3 | 26 valid two-stack | 27 valid three-stack | 28 retreat
Only positions are recorded, not orientations - the replay draws axis-aligned cubes.

Usage: python sites/atlas-pages/tools/build_replays.py
"""
import json
from pathlib import Path
import numpy as np

SITE = Path(__file__).resolve().parent.parent
ROOT = SITE.parent.parent
RUN = ROOT / "experiments/self_imitation/stack_phased_8h_20261023/final_test"

EPISODES = [  # (seed, title, explanation)
    (84002, "Success", "Both placements succeed; the three-cube tower stands for the required 50 frames."),
    (84004, "Success", "A second success in a different part of the table."),
    (84047, "Tower knocked over", "Right after the first placement, as the arm turns toward the third cube, it knocks the two-cube tower over. The third grasp then fails too. This is the second-approach failure the proposal targets."),
    (84001, "Third cube misplaced", "The third cube is grasped and carried but released next to the tower instead of on it."),
]


def episode(seed, title, note):
    rows = {r["seed"]: r for r in json.loads((RUN / "seed1_test3.json").read_text())["rows"]}
    tr = np.load(RUN / f"seed1_test3_traces/{seed}.npz")["trace"]
    cubes, eef = tr[:, 4:13].reshape(-1, 3, 3), tr[:, 13:16]
    # trim idle tail of long failures: keep until nothing moves any more (+40 steps)
    motion = np.r_[0, np.abs(np.diff(np.c_[eef, cubes.reshape(len(tr), -1)], axis=0)).max(1)]
    last = int(np.max(np.where(motion > 5e-4)[0])) if (motion > 5e-4).any() else len(tr) - 1
    end = min(len(tr), last + 40)
    q = lambda a: np.round(a[:end] * 1000, 1).tolist()  # metres -> mm
    return dict(seed=seed, title=title, note=note, success=bool(rows[seed]["success"]),
                steps=len(tr), shown=end,
                cubes=q(cubes.reshape(len(tr), -1)), eef=q(eef),
                grip=np.round(tr[:end, 22], 2).tolist(), stage=tr[:end, 1].astype(int).tolist(),
                phase=tr[:end, 2].astype(int).tolist(), held=tr[:end, 23:26].astype(int).tolist(),
                retreat=tr[:end, 28].astype(int).tolist())


def main():
    data = dict(source="experiments/self_imitation/stack_phased_8h_20261023/final_test (seed 1, 62/100)",
                episodes=[episode(*e) for e in EPISODES])
    out = SITE / "data/replays.js"
    out.write_text("// Generated by tools/build_replays.py - do not edit by hand.\nwindow.REPLAYS = "
                   + json.dumps(data, separators=(",", ":")) + ";\n", encoding="utf-8")
    print(f"wrote {out} ({out.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
