import fs from 'node:fs/promises';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const require = createRequire('C:/Users/artur/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/package.json');
const { Workbook, SpreadsheetFile } = await import(pathToFileURL(require.resolve('@oai/artifact-tool')).href);
const root = 'F:/Desktop/Programmieren/IT/Imitation Learning';
const out = `${root}/outputs/01a17f80-d4ad-76d3-bc0a-25bdf2c9e37f`;
const text = await fs.readFile(`${root}/RESEARCH_NOTIZEN_2026-10-21.md`, 'utf8');
const section = text.split('## 6. Paper-Tabelle')[1].split('## 7.')[0];
const clean = s => s.trim().replace(/<br\s*\/?\s*>/gi, '\n').replace(/\[([^\]]+)\]\(<?([^)>]+)>?\)/g, '$1 ($2)').replace(/\*\*/g, '').replace(/`/g, '');
const rows = section.split(/\r?\n/).filter(l => l.startsWith('|')).filter(l => !/^\|[\s:|-]+$/.test(l)).map(l => l.slice(1,-1).split(/(?<!\\)\|/).map(clean));
if (rows.length !== 9 || rows.some(r => r.length !== 8)) throw new Error('Unexpected source table shape');
await fs.writeFile(`${out}/Paper-Tabelle.csv`, '\ufeff' + rows.map(r=>r.map(v=>'"'+v.replace(/"/g,'""')+'"').join(';')).join('\r\n'), 'utf8');
const wb = Workbook.create();
const sheet = wb.worksheets.add('Paper-Tabelle');
sheet.showGridLines = false;
sheet.getRange('A1:H9').values = rows;
sheet.getRange('A1:H9').format.font = {name:'Arial',size:11};
sheet.getRange('A1:H9').format.wrapText = true;
sheet.getRange('A1:H9').format.verticalAlignment = 'top';
const widths=[34,48,48,48,32,55,55,170];
widths.forEach((w,i)=>sheet.getRangeByIndexes(0,i,9,1).format.columnWidth=w);
sheet.getRange('A1:H1').format.fill = '#243B53';
sheet.getRange('A1:H1').format.font = {name:'Arial',size:11,bold:true,color:'#FFFFFF'};
sheet.getRange('A1:H1').format.rowHeight = 42;
sheet.getRange('A2:H9').format.rowHeight = 390;
for(let r=3;r<=9;r+=2) sheet.getRange(`A${r}:H${r}`).format.fill='#F0F4F8';
sheet.tables.add('A1:H9',true,'PaperTable');
sheet.freezePanes.freezeRows(1);
sheet.freezePanes.freezeColumns(1);
wb.recalculate();
if(JSON.stringify(sheet.getRange('A1:H9').values)!==JSON.stringify(rows)) throw new Error('Data mismatch');
console.log((await wb.inspect({kind:'table',range:'Paper-Tabelle!A1:B3',tableMaxCellChars:80,maxChars:600})).ndjson);
await (await SpreadsheetFile.exportXlsx(wb)).save(`${out}/Paper-Tabelle.xlsx`);
const preview=await wb.render({sheetName:'Paper-Tabelle',range:'A1:C2',scale:1,format:'png'});
await fs.writeFile(`${out}/preview.png`,new Uint8Array(await preview.arrayBuffer()));
console.log(JSON.stringify({papers:rows.length-1,columns:rows[0].length,maxCellLength:Math.max(...rows.flat().map(x=>x.length)),outputs:['Paper-Tabelle.xlsx','Paper-Tabelle.csv']}));
